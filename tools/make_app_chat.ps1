# Writes client/app_chat.js: the game's own generic AI chat lines (the app's
# db/population_chat.yml), so the portraits can leave them out. UTF-8 without BOM.
#
# 3.9.1: companions say these lines too (the engine's chat timer has no per-companion off
# switch, and the table has no import for a mod to change), and the portraits used to show
# them as if they were ours. Re-run after an app update that changes the table:
#   powershell -ExecutionPolicy Bypass -File tools\make_app_chat.ps1 [-Tag v1.7.4]
# Lines with {item}, {map} etc. become patterns; the rest are matched as they are.
param([string]$Tag = 'v1.7.4', [string]$Yml = '')
$root = Split-Path $PSScriptRoot -Parent
if (-not $Yml) {
	$Yml = Join-Path $env:TEMP 'population_chat.yml'
	Invoke-WebRequest "https://raw.githubusercontent.com/Flux159/ragnarokoffline.app/$Tag/third-party/population-engine/files/db/population_chat.yml" -OutFile $Yml -UseBasicParsing
}
$lines = @()
foreach ($l in Get-Content $Yml -Encoding UTF8) {
	if ($l -notmatch '^\s*-\s*"(.*)"\s*$') { continue }
	$t = $Matches[1] -replace '\\"', '"' -replace '\\\\', '\'
	if ($t.Trim()) { $lines += $t.Trim() }
}
$lines = $lines | Sort-Object -Unique
# Lines ours say too ("...", "lol") stay in, so our own aren't lost.
$ours = (Get-ChildItem (Join-Path $root 'npc'), (Join-Path $root 'db') -Recurse -File | ForEach-Object { [IO.File]::ReadAllText($_.FullName) }) -join "`n"
$lines = @($lines | Where-Object { -not ($ours.Contains('"' + $_ + '"') -or $ours.Contains('Say: ' + $_)) })
$js = "// Generated by tools/make_app_chat.ps1 from the app's population_chat.yml ($Tag) -- edit that, not this.`n"
$js += "// The game's own generic AI chat; the portraits leave these lines out (3.9.1).`n"
$js += "export const APP_CHAT = " + (ConvertTo-Json @($lines) -Compress) + ";`n"
[IO.File]::WriteAllText((Join-Path $root 'client\app_chat.js'), $js, (New-Object Text.UTF8Encoding $false))
"app_chat.js: $($lines.Count) lines"
