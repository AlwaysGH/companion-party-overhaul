# companion-party-overhaul 3.10.2: builds npc/companion_quiz_data.txt, the pop quiz's data
# (L_QuizBuild in npc/companion_life.txt reads it with getvariableofnpc).
#   mobs.csv     monsters that spawn in pre-re and where (mobscan.ps1 over rAthena's
#                db/pre-re/mob_db.yml + npc/pre-re/mobs). Element, race, size, level and
#                drops are NOT taken from here: the script asks the server (getmonsterinfo,
#                getmobdrops), so the answers always match the game.
#   regions.tsv  spawn map prefix -> place name (maps not listed are left out)
#   attr_fix.yml rAthena db/pre-re/attr_fix.yml (element damage table)
#   facts.tsv    hand-checked job, skill and card questions
# Run: powershell -File make_quiz.ps1   (writes ..\..\npc\companion_quiz_data.txt)
$ErrorActionPreference = 'Stop'
$here = $PSScriptRoot
$out = Join-Path $here '..\..\npc\companion_quiz_data.txt'
$q = { param($s) '"' + ($s -replace '\\', '\\' -replace '"', '\"') + '"' }

# Places.
$regOf = @{}; $regs = New-Object System.Collections.Generic.List[string]
foreach ($line in Get-Content (Join-Path $here 'regions.tsv')) {
	if ($line -match '^\s*#' -or $line -notmatch '\t') { continue }
	$p, $name = $line -split '\t', 2
	if (-not $regs.Contains($name)) { $regs.Add($name) }
	$regOf[$p] = $regs.IndexOf($name)
}

# Monsters: every place each one spawns in, the busiest first.
$mobs = New-Object System.Collections.Generic.List[object]; $seenName = @{}
foreach ($m in Import-Csv (Join-Path $here 'mobs.csv') | Sort-Object { [int]$_.Id }) {
	if ($m.Name -match 'Treasure|Chest' -or $seenName[$m.Name]) { continue }
	$count = [ordered]@{}
	foreach ($e in $m.Maps -split ' ') {
		$map, $n = $e -split ':'
		$p = $map -replace '\d+$', '' -replace '_$', ''
		if (-not $regOf.ContainsKey($p)) { continue }
		$r = "$($regOf[$p])"; $count[$r] = [int]$count[$r] + [int]$n	# (a string key: an int indexes by position)
	}
	if (-not $count.Count) { continue }
	$seenName[$m.Name] = 1
	$order = $count.GetEnumerator() | Sort-Object Value -Descending | ForEach-Object { $_.Key }
	$mobs.Add([pscustomobject]@{ Id = [int]$m.Id; Regs = ',' + ($order -join ',') + ',' })
}

# Element table: .qa[(lv-1)*100 + attacker*10 + defender] in %.
$ele = 'Neutral', 'Water', 'Earth', 'Fire', 'Wind', 'Poison', 'Holy', 'Dark', 'Ghost', 'Undead'
$atk = New-Object int[] 400; $lv = 0; $a = -1
foreach ($line in Get-Content (Join-Path $here 'attr_fix.yml')) {
	if ($line -match '^\s+- Level: (\d)') { $lv = [int]$matches[1]; continue }
	if ($line -match '^    (\w+):\s*$') { $a = [array]::IndexOf($ele, $matches[1]); continue }
	if ($lv -and $a -ge 0 -and $line -match '^      (\w+): (-?\d+)') {
		$d = [array]::IndexOf($ele, $matches[1]); $atk[($lv - 1) * 100 + $a * 10 + $d] = [int]$matches[2]
	}
}
# Water (1) on Fire (3), Lv 1
if ($atk[1 * 10 + 3] -ne 150) { throw "element table looks wrong (Water on Fire = $($atk[13]))" }

# Facts.
$facts = foreach ($line in Get-Content (Join-Path $here 'facts.tsv')) {
	if ($line -match '^\s*#' -or $line -notmatch '\t') { continue }
	$f = $line -split '\t'
	[pscustomobject]@{ T = $f[0]; Q = $f[1]; A = $f[2]; W1 = $f[3]; W2 = $(if ($f.Count -gt 4) { $f[4] } else { '' }) }
}

$sb = New-Object System.Text.StringBuilder
$add = { param($s) [void]$sb.Append($s).Append("`n") }
function Chunks($name, $vals, $str) {
	for ($i = 0; $i -lt $vals.Count; $i += 40) {
		$part = $vals[$i..([math]::Min($i + 39, $vals.Count - 1))]
		if ($str) { $part = $part | ForEach-Object { & $q $_ } }
		& $add ("`tsetarray .$name[$i], " + ($part -join ', ') + ';')
	}
}
& $add '//===== companion-party-overhaul: pop quiz data (GENERATED by tools/quiz/make_quiz.ps1; edit the'
& $add '//= sources in tools/quiz and run it again). Read by L_QuizBuild (npc/companion_life.txt).'
& $add '//= .rg$ places; .qm monsters with .qr$ their places (",main,other,"); .qa element damage'
& $add '//= (% at (lv-1)*100 + attacker*10 + defender); .fq$/.fa$/.fw1$/.fw2$/.ft$ facts (.fw2$ "" = true/false).'
& $add '-	script	cpo_quiz_data	-1,{'
& $add 'OnInit:'
Chunks 'rg$' @($regs) $true
Chunks 'qm' @($mobs | ForEach-Object Id) $false
Chunks 'qr$' @($mobs | ForEach-Object Regs) $true
Chunks 'qa' @($atk) $false
Chunks 'fq$' @($facts | ForEach-Object Q) $true
Chunks 'fa$' @($facts | ForEach-Object A) $true
Chunks 'fw1$' @($facts | ForEach-Object W1) $true
Chunks 'fw2$' @($facts | ForEach-Object W2) $true
Chunks 'ft$' @($facts | ForEach-Object T) $true
& $add ("`t.nrg = $($regs.Count);`n`t.nqm = $($mobs.Count);`n`t.nf = $(@($facts).Count);")
& $add "`tend;"
& $add '}'
[IO.File]::WriteAllText([IO.Path]::GetFullPath($out), $sb.ToString(), (New-Object System.Text.UTF8Encoding($false)))
"places $($regs.Count), monsters $($mobs.Count), facts $(@($facts).Count) -> $out"
"questions: monsters x 9 kinds = $($mobs.Count * 9), element pairs 100, facts $(@($facts).Count): about $($mobs.Count * 9 + 100 + @($facts).Count)"
